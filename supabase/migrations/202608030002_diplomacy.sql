create or replace function public.tlr_relation_total(
  p_source text,
  p_target text,
  p_world_date date
) returns integer
language sql stable
as $$
  select greatest(-100, least(100,
    r.base_score + coalesce(sum(m.value) filter (
      where (m.starts_world_date is null or m.starts_world_date <= p_world_date)
        and (m.ends_world_date is null or m.ends_world_date >= p_world_date)
    ), 0)
  ))::integer
  from public.country_relations r
  left join public.country_relation_modifiers m
    on m.source_country_key = r.source_country_key
   and m.target_country_key = r.target_country_key
  where r.source_country_key = p_source and r.target_country_key = p_target
  group by r.base_score;
$$;

create or replace function public.tlr_change_relation(
  p_source text,
  p_target text,
  p_amount integer,
  p_reason text,
  p_source_type text,
  p_source_reference text,
  p_world_date date
) returns integer
language plpgsql
as $$
declare
  v_previous integer;
  v_next integer;
begin
  if p_source = p_target then raise exception 'SELF_RELATION'; end if;
  insert into public.country_relations(source_country_key, target_country_key, base_score)
  values (p_source, p_target, 0)
  on conflict (source_country_key, target_country_key) do nothing;
  select base_score into v_previous from public.country_relations
    where source_country_key = p_source and target_country_key = p_target for update;
  v_next := greatest(-100, least(100, v_previous + p_amount));
  update public.country_relations set base_score = v_next, updated_at = now()
    where source_country_key = p_source and target_country_key = p_target;
  insert into public.country_relation_history(
    source_country_key, target_country_key, previous_score, change_amount,
    next_score, reason, source_type, source_reference, world_date
  ) values (
    p_source, p_target, v_previous, v_next - v_previous,
    v_next, p_reason, p_source_type, p_source_reference, p_world_date
  );
  return v_next;
end;
$$;

create or replace function public.tlr_expire_diplomacy(p_world_date date)
returns void language plpgsql as $$
declare v_row record;
begin
  for v_row in
    update public.diplomatic_proposals
      set status = 'EXPIRED', updated_at = now()
      where status = 'PENDING' and response_deadline_world_date < p_world_date
      returning *
  loop
    insert into public.diplomacy_events(actor_country_key, counterpart_country_key, event_type, proposal_id, world_date)
      values (v_row.proposer_country_key, v_row.receiver_country_key, 'PROPOSAL_EXPIRED', v_row.id, p_world_date);
    insert into public.diplomacy_notifications(recipient_country_key, counterpart_country_key, notification_type, proposal_id)
      values
        (v_row.proposer_country_key, v_row.receiver_country_key, 'PROPOSAL_EXPIRED', v_row.id),
        (v_row.receiver_country_key, v_row.proposer_country_key, 'PROPOSAL_EXPIRED', v_row.id);
  end loop;
  update public.diplomatic_agreements set status = 'ACTIVE', updated_at = now()
    where status = 'SCHEDULED' and starts_world_date <= p_world_date;
  update public.diplomatic_agreements set status = 'EXPIRED', updated_at = now()
    where status in ('SCHEDULED', 'ACTIVE') and ends_world_date is not null and ends_world_date < p_world_date;
end;
$$;

create or replace function public.tlr_apply_diplomatic_action(
  p_source text,
  p_target text,
  p_action_type text,
  p_world_date date
) returns integer language plpgsql as $$
declare v_amount integer; v_next integer; v_available date;
begin
  if p_source = p_target then raise exception 'SELF_TARGET'; end if;
  if p_action_type = 'IMPROVE_RELATIONS' then v_amount := 5;
  elsif p_action_type = 'WORSEN_RELATIONS' then v_amount := -5;
  else raise exception 'UNKNOWN_ACTION'; end if;
  select available_world_date into v_available from public.diplomatic_action_cooldowns
    where country_key = p_source and target_country_key = p_target and action_type = p_action_type for update;
  if v_available is not null and v_available > p_world_date then raise exception 'ACTION_COOLDOWN'; end if;
  v_next := public.tlr_change_relation(p_source, p_target, v_amount,
    case when v_amount > 0 then '관계 개선' else '관계 악화' end,
    'DIPLOMATIC_ACTION', p_action_type, p_world_date);
  insert into public.diplomatic_action_cooldowns(country_key, target_country_key, action_type, available_world_date)
    values (p_source, p_target, p_action_type, p_world_date + 7)
    on conflict (country_key, target_country_key, action_type)
    do update set available_world_date = excluded.available_world_date;
  insert into public.diplomacy_events(actor_country_key, counterpart_country_key, event_type, detail, world_date)
    values (p_source, p_target, p_action_type, jsonb_build_object('amount', v_amount), p_world_date);
  return v_next;
end;
$$;

create or replace function public.tlr_create_diplomatic_proposal(
  p_proposer text,
  p_receiver text,
  p_type text,
  p_review_route text,
  p_terms jsonb,
  p_start date,
  p_end date,
  p_deadline date,
  p_world_date date
) returns uuid language plpgsql as $$
declare v_id uuid;
begin
  if p_proposer = p_receiver then raise exception 'SELF_TARGET'; end if;
  if p_deadline < p_world_date then raise exception 'INVALID_DEADLINE'; end if;
  if p_start < p_world_date then raise exception 'INVALID_START_DATE'; end if;
  if p_end is not null and p_end < p_start then raise exception 'INVALID_END_DATE'; end if;
  if exists (
    select 1 from public.diplomatic_agreements
    where country_a_key = least(p_proposer, p_receiver)
      and country_b_key = greatest(p_proposer, p_receiver)
      and agreement_type = case p_type
        when 'NON_AGGRESSION' then 'NON_AGGRESSION'
        when 'TRADE_AGREEMENT' then 'TRADE_AGREEMENT'
        when 'FACTION_INVITATION' then 'FACTION_MEMBERSHIP'
        when 'MILITARY_ACCESS' then 'MILITARY_ACCESS'
        else 'INDEPENDENCE_GUARANTEE' end
      and status in ('SCHEDULED', 'ACTIVE')
  ) then raise exception 'AGREEMENT_EXISTS'; end if;
  insert into public.diplomatic_proposals(
    proposer_country_key, receiver_country_key, proposal_type, review_route,
    terms, proposed_start_world_date, proposed_end_world_date,
    response_deadline_world_date, sent_world_date
  ) values (
    p_proposer, p_receiver, p_type, p_review_route, coalesce(p_terms, '{}'::jsonb),
    p_start, p_end, p_deadline, p_world_date
  ) returning id into v_id;
  insert into public.diplomacy_events(actor_country_key, counterpart_country_key, event_type, proposal_id, world_date)
    values (p_proposer, p_receiver, 'PROPOSAL_SENT', v_id, p_world_date);
  if p_review_route = 'PLAYER' then
    insert into public.diplomacy_notifications(recipient_country_key, counterpart_country_key, notification_type, proposal_id)
      values (p_receiver, p_proposer, 'PROPOSAL_RECEIVED', v_id);
  end if;
  return v_id;
exception when unique_violation then
  raise exception 'DUPLICATE_PENDING_PROPOSAL';
end;
$$;

create or replace function public.tlr_respond_diplomatic_proposal(
  p_proposal_id uuid,
  p_receiver text,
  p_response text,
  p_user_id uuid,
  p_world_date date
) returns uuid language plpgsql as $$
declare v_row public.diplomatic_proposals%rowtype; v_agreement_id uuid; v_agreement_type text;
begin
  select * into v_row from public.diplomatic_proposals where id = p_proposal_id for update;
  if not found then raise exception 'PROPOSAL_NOT_FOUND'; end if;
  if v_row.status <> 'PENDING' then raise exception 'PROPOSAL_NOT_PENDING'; end if;
  if v_row.receiver_country_key <> p_receiver then raise exception 'NOT_PROPOSAL_RECEIVER'; end if;
  if v_row.response_deadline_world_date < p_world_date then
    update public.diplomatic_proposals set status = 'EXPIRED', updated_at = now() where id = p_proposal_id;
    raise exception 'PROPOSAL_EXPIRED';
  end if;
  if p_response not in ('ACCEPTED', 'REJECTED') then raise exception 'INVALID_RESPONSE'; end if;
  update public.diplomatic_proposals set status = p_response, responded_world_date = p_world_date,
    responded_by_user_id = p_user_id, updated_at = now() where id = p_proposal_id;
  insert into public.diplomacy_events(actor_country_key, counterpart_country_key, event_type, proposal_id, world_date)
    values (p_receiver, v_row.proposer_country_key, 'PROPOSAL_' || p_response, p_proposal_id, p_world_date);
  insert into public.diplomacy_notifications(recipient_country_key, counterpart_country_key, notification_type, proposal_id)
    values (v_row.proposer_country_key, p_receiver,
      case when p_response = 'ACCEPTED' then 'PROPOSAL_ACCEPTED' else 'PROPOSAL_REJECTED' end,
      p_proposal_id);
  if p_response = 'REJECTED' then return null; end if;
  v_agreement_type := case v_row.proposal_type
    when 'NON_AGGRESSION' then 'NON_AGGRESSION'
    when 'TRADE_AGREEMENT' then 'TRADE_AGREEMENT'
    when 'FACTION_INVITATION' then 'FACTION_MEMBERSHIP'
    when 'MILITARY_ACCESS' then 'MILITARY_ACCESS'
    else 'INDEPENDENCE_GUARANTEE' end;
  insert into public.diplomatic_agreements(
    country_a_key, country_b_key, agreement_type, status, starts_world_date,
    ends_world_date, terms, created_from_proposal_id
  ) values (
    least(v_row.proposer_country_key, v_row.receiver_country_key),
    greatest(v_row.proposer_country_key, v_row.receiver_country_key),
    v_agreement_type,
    case when v_row.proposed_start_world_date <= p_world_date then 'ACTIVE' else 'SCHEDULED' end,
    v_row.proposed_start_world_date, v_row.proposed_end_world_date, v_row.terms, v_row.id
  ) returning id into v_agreement_id;
  perform public.tlr_change_relation(v_row.proposer_country_key, v_row.receiver_country_key,
    case when v_row.proposal_type = 'TRADE_AGREEMENT' then 10 else 5 end,
    '외교 제안 수락', 'TREATY', v_agreement_id::text, p_world_date);
  perform public.tlr_change_relation(v_row.receiver_country_key, v_row.proposer_country_key,
    case when v_row.proposal_type = 'TRADE_AGREEMENT' then 7 else 5 end,
    '외교 제안 수락', 'TREATY', v_agreement_id::text, p_world_date);
  insert into public.diplomacy_events(actor_country_key, counterpart_country_key, event_type, proposal_id, agreement_id, world_date)
    values (v_row.proposer_country_key, v_row.receiver_country_key, 'AGREEMENT_CREATED', v_row.id, v_agreement_id, p_world_date);
  insert into public.diplomacy_notifications(recipient_country_key, counterpart_country_key, notification_type, proposal_id, agreement_id)
    values
      (v_row.proposer_country_key, v_row.receiver_country_key, 'AGREEMENT_CREATED', v_row.id, v_agreement_id),
      (v_row.receiver_country_key, v_row.proposer_country_key, 'AGREEMENT_CREATED', v_row.id, v_agreement_id);
  return v_agreement_id;
end;
$$;

create or replace function public.tlr_withdraw_diplomatic_proposal(
  p_proposal_id uuid,
  p_proposer text,
  p_world_date date
) returns void language plpgsql as $$
declare v_row public.diplomatic_proposals%rowtype;
begin
  select * into v_row from public.diplomatic_proposals where id = p_proposal_id for update;
  if not found then raise exception 'PROPOSAL_NOT_FOUND'; end if;
  if v_row.proposer_country_key <> p_proposer then raise exception 'NOT_PROPOSAL_PROPOSER'; end if;
  if v_row.status <> 'PENDING' then raise exception 'PROPOSAL_NOT_PENDING'; end if;
  update public.diplomatic_proposals set status = 'WITHDRAWN', updated_at = now() where id = p_proposal_id;
  update public.diplomacy_notifications set dismissed_at = now()
    where proposal_id = p_proposal_id and notification_type = 'PROPOSAL_RECEIVED';
  insert into public.diplomacy_events(actor_country_key, counterpart_country_key, event_type, proposal_id, world_date)
    values (p_proposer, v_row.receiver_country_key, 'PROPOSAL_WITHDRAWN', p_proposal_id, p_world_date);
  insert into public.diplomacy_notifications(recipient_country_key, counterpart_country_key, notification_type, proposal_id)
    values (v_row.receiver_country_key, p_proposer, 'PROPOSAL_WITHDRAWN', p_proposal_id);
end;
$$;

