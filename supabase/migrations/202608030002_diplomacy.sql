  update public.diplomacy_notifications
    set dismissed_at = now()
    where proposal_id = p_proposal_id and notification_type = 'PROPOSAL_RECEIVED';
  insert into public.diplomacy_events(
    actor_country_key, counterpart_country_key, event_type, proposal_id, world_date
  ) values (
    v_proposal.receiver_country_key, v_proposal.proposer_country_key,
    'PROPOSAL_CANCELLED_BY_ADMIN', p_proposal_id, p_world_date
  );
  insert into public.diplomacy_notifications(
    recipient_country_key, counterpart_country_key, notification_type, proposal_id
  ) values (
    v_proposal.proposer_country_key, v_proposal.receiver_country_key,
    'ADMIN_CANCELLED', p_proposal_id
  );
  insert into public.diplomacy_admin_reviews(
    proposal_id, admin_subject, admin_kind, proposer_country_key,
    receiver_country_key, decision, world_date
  ) values (
    p_proposal_id, p_admin_subject, p_admin_kind, v_proposal.proposer_country_key,
    v_proposal.receiver_country_key, 'CANCELLED', p_world_date
  );
end;
$$;

